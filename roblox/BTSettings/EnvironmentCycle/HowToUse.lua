এটা কী করে?
	আসল ঘড়ি দেখে প্রতি ২ ঘণ্টা পর পর পুরো গেমের সব প্লেয়ারের এনভায়রনমেন্ট (আকাশ, লাইটিং,
	অ্যাটমোস্ফিয়ার, ইফেক্ট, ঘাসের রং, মেঘ) একসাথে বদলে দেয় — "All Lighting"
	ফোল্ডারের প্রিসেট থেকে। বদলানোর সময় ধীরে ধীরে (smooth) বদলায় আর সবার
	স্ক্রিনের উপরে ছোট একটা কার্ড আসে:  🌙 ENVIRONMENT CHANGED · Night

ফাইলগুলো (সব এই EnvironmentCycle ফোল্ডারের ভেতরেই থাকবে, সরাবেন না):
	Settings  ← শুধু এটাই এডিট করবেন
	Server    ← Script, RunContext = Server (কোন প্রিসেট এখন চলবে ঠিক করে)
	Client    ← Script, RunContext = Client (প্রতিটা ফোনে/পিসিতে প্রিসেট বসায় + কার্ড দেখায়)
	HowToUse  ← এই গাইড
	RunContext থাকার কারণে Server আর Client স্ক্রিপ্ট ReplicatedStorage-এর
	ভেতর থেকেই চলে — ServerScriptService বা StarterPlayerScripts-এ কিছু রাখতে
	হবে না।

BTSettings Config-এ শুধু একটা জিনিস যোগ হয়েছে:
	Settings › Graphics ট্যাবে "Live environment" টগল (id = "env_live")।
	বাকি সব Config থেকে এই সিস্টেম শুধু পড়ে (All Lighting ফোল্ডারের নাম,
	থিমের রং, ফন্ট, quality preset), কিছু বদলায় না।


──────────────────────────────────────────────────────────────────────────────
১) কীভাবে দিন সাজানো হয় — ৩টা নিয়ম
──────────────────────────────────────────────────────────────────────────────
	সব সময় বাংলাদেশ সময়ে (Settings.utcOffsetHours = 6)। হিসাবটা শুধু আসল
	ঘড়ি দিয়ে হয়, তাই গেমের সব সার্ভারে, এমনকি Studio-তেও, একই মুহূর্তে একই
	এনভায়রনমেন্ট থাকে। প্রতিদিন একই সময়ে একই জিনিস।

	ক) লুপ — এগুলো পালা করে আসে, প্রতিটা blockHours (২ ঘণ্টা) থাকে:
		Settings.blockHours = 2
		Settings.loop = {
			{ preset = "Sunrise", title = "Sunrise", icon = "🌅" },
			{ preset = "Day", ... },
			{ preset = "AfternoonGoldenHour", ... },
			{ preset = "Sunset", ... },
			{ preset = "Night", ... },
		}

	খ) নির্দিষ্ট সময় — এই সময় হলে এই প্রিসেট আসবেই, তারপর লুপ সেখান থেকে চলে:
		Settings.fixedTimes = {
			{ at = "06:00", preset = "Sunrise" },
			{ at = "20:00", preset = "Night" },
		}
		পরের নির্দিষ্ট সময় চলে এলে চলতি প্রিসেট একটু আগেই শেষ হয়ে যায়।

	গ) শুধু এই সময়ের মধ্যে — এর বাইরে লুপে পালা এলে বাদ দিয়ে পরেরটা আসে:
		Settings.onlyBetween = {
			Night = { from = "19:00", to = "05:00" },   -- Night শুধু রাতে
			Sunrise = { from = "05:00", to = "09:00" }, -- Sunrise শুধু ভোরে
		}

	এই সেটিংয়ে একটা দিন (বাংলাদেশ সময়):
		06-08 Sunrise      (সকাল ৬টার নির্দিষ্ট সময়)
		08-10 Day
		10-12 Afternoon
		12-14 Sunset
		14-16 Day          (দিনে Night আর Sunrise বাদ)
		16-18 Afternoon
		18-20 Sunset
		20-22 Night        (রাত ৮টার নির্দিষ্ট সময়)
		22-00 Day          (Night ২ ঘণ্টা থেকে চলে গেছে)
		00-02 Afternoon
		02-04 Sunset
		04-06 Night        (রাত, তাই Night আসতে পারে)
		06:00 আবার Sunrise — পরের দিন হুবহু একই

	লাইনের ঐচ্ছিক জিনিস: title (কার্ডে নাম), icon (ইমোজি), color (কার্ডের রং),
	message (নামের নিচে ছোট লাইন), clockTime (সূর্যের অবস্থান 0-24, যেমন রাতে
	চাঁদের জন্য 0), transitionTime (শুধু এই প্রিসেটের ব্লেন্ড সেকেন্ড)।
	preset = "All Lighting"-এর ভেতরের ফোল্ডারের নাম (বড়/ছোট হাতের অক্ষর না
	মিললেও চলে)। ভুল নাম/সময় হলে Output-এ "[BTSettings] Environment: ..."
	ওয়ার্নিং আসে, ওই লাইন বাদ যায়, বাকি সব চলে।


──────────────────────────────────────────────────────────────────────────────
২) Studio-তে টেস্ট
──────────────────────────────────────────────────────────────────────────────
	• Play চাপলে আপনার কম্পিউটারের ঘড়ি দেখে এখনকার এনভায়রনমেন্ট আসে।
	  যেমন রাত ২টায় Play করলে Sunset (02-04), রাত ৯টায় Night।
	• চ্যাটে /env লিখলে দেখাবে এখন কী আর পরে কী আসবে।
	• দ্রুত বদলানো দেখতে: blockHours = 0.01 (প্রায় ৩৬ সেকেন্ড), দেখা শেষে
	  আবার 2 করে দিন। অথবা /env next দিয়ে একটা একটা করে দেখুন।


──────────────────────────────────────────────────────────────────────────────
৩) বদলানোর ধরন — Settings.transition
──────────────────────────────────────────────────────────────────────────────
	time = 6          লাইটিং/কুয়াশা/ইফেক্ট কত সেকেন্ডে ধীরে ধীরে বদলাবে
	skyFade = 0.8     আকাশের ছবি বদলানোর সময় হালকা অন্ধকার হওয়ার সময়
	skyDim = 0.35     কতটা অন্ধকার হবে (0 = একদম না)
	clockDirection    "shortest" = ঘড়ির ছোট পথে, "forward" = সবসময় সামনে (টাইম-ল্যাপস)
	instantOnJoin     নতুন প্লেয়ার ঢুকলে সাথে সাথে বসবে, ব্লেন্ড ছাড়া


──────────────────────────────────────────────────────────────────────────────
৪) ছোট কার্ড (নোটিস) — Settings.notice
──────────────────────────────────────────────────────────────────────────────
	enabled, header, duration (কত সেকেন্ড থাকবে), position ("Top"/"Bottom"),
	showNext ("Next: Sunset in 1h 59m" লাইন), shine (কার্ডে হালকা আলোর ঝলক),
	mobileScale (ফোনে সাইজ), soundId (চাইলে ছোট সাউন্ড)।
	style = "panel" দিলে নিজের কার্ডের বদলে BTSettings-এর সাধারণ পপ-আপ আসবে।
	যে প্লেয়ার Settings-এ "Pop-up messages" বন্ধ রেখেছে, তার কাছে কার্ড আসবে না
	(respectPopupToggle = false দিলে সবাই দেখবে)। কার্ডের রং Config.theme থেকে।


──────────────────────────────────────────────────────────────────────────────
৫) প্লেয়ারের নিজের পছন্দ
──────────────────────────────────────────────────────────────────────────────
	• Skybox ট্যাব থেকে প্লেয়ার যেকোনো সময় নিজের আকাশ বেছে নিতে পারে — সেটা
	  পরের এনভায়রনমেন্ট বদলানো পর্যন্ত থাকে।
	• Graphics › "Live environment" বন্ধ করলে তার ফোনে আর বদলাবে না, নোটিসও
	  আসবে না; তখনকার আকাশই থাকে। আবার চালু করলে সাথে সাথে এখনকারটা আসে।
	  এটা সেভ হয় না — প্রতিবার গেমে ঢুকলে চালু অবস্থায় থাকে।
	• Quality "Low" থাকলে নতুন প্রিসেটেও post effects বন্ধ থাকে আর কুয়াশা পাতলা
	  থাকে (Settings.player.respectQualityPreset)।
	• "Reset lighting" চাপলে (আর নিজের আকাশ বাছা না থাকলে) লাইভ এনভায়রনমেন্টই
	  ফিরে আসে।


──────────────────────────────────────────────────────────────────────────────
৬) গেম চলার সময় নিজে বদলানো (অ্যাডমিন)
──────────────────────────────────────────────────────────────────────────────
	Settings.admin.userIds = { 123456789 }   ← আপনার Roblox User ID দিন
	(গেমের মালিক / গ্রুপের মালিক এমনিতেই পারে; Studio-তে টেস্টে সবাই পারে)

	চ্যাটে লিখুন:
		/env              এখন কী চলছে, পরে কী আসবে
		/env list         সব প্রিসেটের নাম
		/env Night        এই সার্ভারে এখনই Night (blockHours পর্যন্ত)
		/env Night 30     Night থাকবে 30 মিনিট — তারপর আবার টাইমার
		/env Pink SKy 10  নামে স্পেস থাকলেও চলে
		/env next         পরেরটায় চলে যাও
		/env auto         নিজের বদলানো বাতিল, আবার টাইমার
	উত্তর শুধু আপনার স্ক্রিনে ছোট কার্ডে আসে। কমান্ড শুধু আপনি যে সার্ভারে
	আছেন সেটাকেই বদলায়।

	অন্য সার্ভার স্ক্রিপ্ট থেকে (যেমন কোনো ইভেন্ট শুরু হলে রাত করে দেওয়া):
		local cmd = game.ReplicatedStorage.BTSettings.EnvironmentCycle:WaitForChild("Command")
		cmd:Invoke("set", "Night", 30)
		cmd:Invoke("next")
		cmd:Invoke("auto")
		print(cmd:Invoke("status"))

	অন্য স্ক্রিপ্ট থেকে এখনকার অবস্থা পড়া (সার্ভার বা ক্লায়েন্ট):
		local env = game.ReplicatedStorage.BTSettings.EnvironmentCycle
		env:GetAttribute("Preset")      -- "Night"
		env:GetAttribute("EndsAt")      -- কখন শেষ (workspace:GetServerTimeNow()-এর সাথে তুলনা)
		env:GetAttributeChangedSignal("ChangeId"):Connect(function() ... end)


──────────────────────────────────────────────────────────────────────────────
৭) নতুন প্রিসেট যোগ করা
──────────────────────────────────────────────────────────────────────────────
	১. "All Lighting"-এ নতুন ফোল্ডার (অন্যগুলোর মতো: Sky, Atmosphere, Bloom,
	   ColorCorrection, SunRays ... আর "Lighting Valus" ফোল্ডার)।
	২. Settings.loop-এ এক লাইন: { preset = "ফোল্ডারের নাম", title = "নাম" }
	প্রতিটা প্রিসেট থেকে যা বসে:
	   • Sky, Atmosphere, সব PostEffect (প্রথমটা, প্রতি ধরনের একটা করে)
	   • "Lighting Valus"-এর যেসব নাম Lighting-এর প্রপার্টির সাথে মেলে
	     (Ambient, Brightness, ClockTime, ExposureCompensation ...)
	   • "Grass Color" → টেরেইনের ঘাসের রং (না থাকলে ম্যাপের আসল ঘাসের রং)
	   • ফোল্ডারের ModuleScript-এর "Clouds = {...}" → Terrain-এ Clouds থাকলে


──────────────────────────────────────────────────────────────────────────────
৮) সমস্যা হলে
──────────────────────────────────────────────────────────────────────────────
	• Output-এ "[BTSettings] Environment:" দিয়ে শুরু লাইনগুলো দেখুন।
	• কিছুই বদলাচ্ছে না → Settings.enabled = true? Server আর Client স্ক্রিপ্টের
	  RunContext ঠিক আছে (Server / Client)? Enabled চালু আছে?
	• কার্ড আসছে না → Settings › "Pop-up messages" চালু? notice.enabled = true?
	• রাতে সূর্য দেখা যাচ্ছে → ওই লাইনে clockTime = 0 দিন (বা প্রিসেটের
	  Lighting Valus > ClockTime বদলান)।
